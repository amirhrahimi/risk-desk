<#
.SYNOPSIS
    Writes broker-profiles/SUMMARY.md, a short digest of the BrokerProbe and
    GatewaySmoke reports in broker-profiles/.

.DESCRIPTION
    A probe report is about 90 KB (28+ symbols with every property). SUMMARY.md
    keeps, for every account (latest probe per login):
      - the account line (currency, leverage, margin mode, order limit, build),
      - one row per test-matrix role from the probe's [test symbols] (EURUSD,
        USDJPY, cross, XAUUSD, US30, Nasdaq 100, BTCUSD, whole-contract CFD)
        with the properties the BC rules depend on,
      - the probe's own "items to check",
      - the latest GatewaySmoke result per symbol, with any FAIL/SKIP rows.
    Read SUMMARY.md first. For a property or symbol it does not show, search the
    raw report for its "[symbol NAME]" section instead of reading the whole file.
    Run this again after copying a new probe or smoke report into broker-profiles/.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File build/summarize-profiles.ps1
#>
param(
    [string]$ProfilesDir = (Join-Path (Split-Path -Parent $PSScriptRoot) 'broker-profiles')
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version 2.0

# test-matrix account ids (docs/08-testing.md section 4), matched on company and platform
$AccountIds = @(
    @{ Id = 'A1'; Company = '^IG ';           Platform = 'MT4' },
    @{ Id = 'A2'; Company = '^IC Markets';    Platform = 'MT4' },
    @{ Id = 'A3'; Company = '^IC Markets';    Platform = 'MT5' },
    @{ Id = 'A4'; Company = '^Dukascopy';     Platform = 'MT4' },
    @{ Id = 'A5'; Company = '^Dukascopy';     Platform = 'MT5' },
    @{ Id = 'A6'; Company = '^MetaQuotes';    Platform = 'MT5' }
)

function Read-Report([string]$path) {
    # section name -> ordered key/value map of its 2-space-indented lines
    $sections = [ordered]@{}
    $s = $null
    foreach ($line in [IO.File]::ReadAllLines($path)) {
        if ($line -match '^\[(.+)\]\s*$') {
            $s = [ordered]@{ '_fills' = @(); '_items' = @() }
            $sections[$Matches[1]] = $s
            continue
        }
        if ($null -eq $s) { continue }
        if ($line -match '^  - (.*)$') { $s['_items'] += $Matches[1].Trim(); continue }
        if ($line -match '^  (\S[^:]*?):\s+(.*)$') {
            if (-not $s.Contains($Matches[1])) { $s[$Matches[1]] = $Matches[2].Trim() }
            continue
        }
        if ($line -match '^\s+market_buy fill=(\w+):\s+ok=true') { $s['_fills'] += $Matches[1] }
    }
    return $sections
}

function Get-Val($section, [string]$key) {
    if ($null -ne $section -and $section.Contains($key)) { return [string]$section[$key] }
    return ''
}
function Format-NoCode([string]$v) { return ($v -replace '\s*\(\d+\)$', '') }   # 'full (4)' -> 'full'
function Format-Points([string]$v)  { return ($v -replace '\s*pts.*$', '') }     # '40 pts (0.0004)' -> '40'
function Esc([string]$v)        { return ($v -replace '\|', '\|') }

function Get-AccountId([string]$company, [string]$platform) {
    foreach ($a in $AccountIds) {
        if ($platform -eq $a.Platform -and $company -match $a.Company) { return $a.Id }
    }
    return '-'
}

$out = New-Object System.Collections.Generic.List[string]
$out.Add('# Broker profiles: summary')
$out.Add('')
$out.Add('Generated by `build/summarize-profiles.ps1` from the reports in this folder. Do not edit by hand: run the script again after adding a report.')
$out.Add('For a property or symbol not shown here, search the raw probe for its `[symbol NAME]` section (about 60 lines) instead of reading the whole file.')
$out.Add('')
$out.Add('Columns: tick value is per 1 lot and one tick, in the account currency. Stops / freeze and spread in points. Filling (MT5 only) shows the symbol flags, then the fillings OrderCheck accepted for a market buy. MT4 has no filling or expiration flags.')

# latest probe per platform + login. The login part is the numeric login of
# a raw report or the label of a report redacted by build/redact-report.ps1.
$probes = @(Get-ChildItem -LiteralPath $ProfilesDir -Filter 'probe_*.txt' -File | ForEach-Object {
    if ($_.Name -match '^probe_(.+)_(MT4|MT5)_(\d+|[A-Za-z][A-Za-z0-9]{0,7})_(\d{8})\.txt$') {
        [pscustomobject]@{ File = $_; Platform = $Matches[2]; Login = $Matches[3]; Date = $Matches[4] }
    }
} | Group-Object Platform, Login | ForEach-Object { $_.Group | Sort-Object Date | Select-Object -Last 1 })

$rows = @()
foreach ($p in $probes) {
    $r = Read-Report $p.File.FullName
    $acc = $r['account']
    $company = Get-Val $acc 'company'
    $rows += [pscustomobject]@{ Probe = $p; Report = $r; Company = $company; Id = (Get-AccountId $company $p.Platform) }
}

foreach ($row in @($rows | Sort-Object Id, Login)) {
    $p = $row.Probe; $r = $row.Report
    $acc = $r['account']; $term = $r['terminal']; $sum = $r['summary']
    $out.Add('')
    $loginPart = if ($p.Login -eq $row.Id) { '' } else { " - $($p.Login)" }
    $out.Add("## $($row.Id) $($row.Company) $($p.Platform)$loginPart @ $(Get-Val $acc 'server')")
    $out.Add('')
    $out.Add("Currency $(Get-Val $acc 'currency'), leverage $(Get-Val $acc 'leverage'), $(Get-Val $acc 'trade_mode'), margin mode $(Get-Val $acc 'margin_mode'), order limit $(Get-Val $acc 'limit_orders'), terminal build $(Get-Val $term 'build'). " +
             "Probe ``$($p.File.Name)`` ($(Get-Val $sum 'symbols_probed') symbols).")
    $out.Add('')
    $out.Add('| Role | Symbol | Ccy base/profit/margin | Digits | Tick size | Tick value | Contract | Vol min / step / max | Stops / freeze | Trade | Exec | Calc | Filling | Expiration | Spread | Spec check |')
    $out.Add('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
    $roles = $r['test symbols']
    if ($null -ne $roles) {
        foreach ($role in @($roles.Keys | Where-Object { -not $_.StartsWith('_') })) {
            $cands = [string]$roles[$role]
            $name = ''
            if ($cands -ne 'none found') { $name = ($cands -split ',')[0] -replace '\s*\(.*$', '' }
            $note = ''
            $roleName = ($role -replace '\s*\(.*$', '')
            if ($name -eq '' -and $r.Contains("symbol $roleName")) { $name = $roleName; $note = ' (by name)' }
            if ($name -eq '' -or -not $r.Contains("symbol $name")) {
                $out.Add("| $role | none found | | | | | | | | | | | | | | |")
                continue
            }
            $s = $r["symbol $name"]
            $fill = (Format-NoCode (Get-Val $s 'filling_flags')) -replace '\|', ','
            if (@($s['_fills']).Count -gt 0) { $fill = "$fill; ok: $(@($s['_fills']) -join ',')" }
            $expiry = (Format-NoCode (Get-Val $s 'expiration_flags')) -replace '\|', ','
            if ($p.Platform -eq 'MT4') { $fill = '-'; $expiry = '-' }
            $cells = @(
                $role, "$name$note",
                "$(Get-Val $s 'currency_base')/$(Get-Val $s 'currency_profit')/$(Get-Val $s 'currency_margin')",
                (Get-Val $s 'digits'), (Get-Val $s 'tick_size'), (Get-Val $s 'tick_value'), (Get-Val $s 'contract_size'),
                "$(Get-Val $s 'volume_min') / $(Get-Val $s 'volume_step') / $(Get-Val $s 'volume_max')",
                "$(Format-Points (Get-Val $s 'stops_level')) / $(Format-Points (Get-Val $s 'freeze_level'))",
                (Format-NoCode (Get-Val $s 'trade_mode')), (Format-NoCode (Get-Val $s 'exec_mode')), (Format-NoCode (Get-Val $s 'calc_mode')),
                $fill, $expiry, ((Get-Val $s 'spread_now') -replace ' pts$', ''),
                ((Get-Val $s 'spec_check') -replace '^OK - Symbol spec OK$', 'OK')
            )
            $out.Add('| ' + ((@($cells) | ForEach-Object { Esc ([string]$_) }) -join ' | ') + ' |')
        }
    }
    # probe items: the buy and sell lines and the symbols with the same finding are merged into one line
    $groups = [ordered]@{}
    if ($null -ne $sum) {
        foreach ($i in @($sum['_items'])) {
            $norm = ([string]$i) -replace '\(loss_100ticks_(buy|sell), ', '(' -replace '\s*\(loss_100ticks_(buy|sell)\)', ''
            $sym = ''; $msg = $norm
            if ($norm -match '^(\S+?): (.*)$') { $sym = $Matches[1]; $msg = $Matches[2] }
            if (-not $groups.Contains($msg)) { $groups[$msg] = New-Object System.Collections.Generic.List[string] }
            if ($sym -ne '' -and -not $groups[$msg].Contains($sym)) { $groups[$msg].Add($sym) }
        }
    }
    $out.Add('')
    if ($groups.Count -eq 0) { $out.Add('Probe items to check: none.') }
    else {
        $out.Add('Probe items to check:')
        foreach ($msg in $groups.Keys) { $out.Add("- $(($groups[$msg]) -join ', '): $msg") }
    }

    # GatewaySmoke: the file holds one block per run, the latest run per symbol is shown
    $smokeFile = Get-ChildItem -LiteralPath $ProfilesDir -Filter "smoke_*_$($p.Platform)_$($p.Login)_*.txt" -File | Sort-Object Name | Select-Object -Last 1
    $out.Add('')
    if (-not $smokeFile) { $out.Add('GatewaySmoke: no report.'); continue }
    $runs = [ordered]@{}
    $cur = $null
    foreach ($line in [IO.File]::ReadAllLines($smokeFile.FullName)) {
        if ($line -match '^# RiskDesk GatewaySmoke (\S+) - (.+?) - (.+)$') {
            $cur = [pscustomobject]@{ Version = $Matches[1]; Time = $Matches[2]; Symbol = $Matches[3].Trim(); Summary = ''; Rows = @() }
            $runs[$cur.Symbol] = $cur    # a later run of the same symbol replaces the earlier one
            continue
        }
        if ($null -eq $cur) { continue }
        if ($line -match '^\s+PASS \d+, FAIL \d+, SKIP \d+') { $cur.Summary = $line.Trim(); continue }
        if ($line -match '^\s+\S+\s+.+?\s+(FAIL|SKIP)\s+\d+') { $cur.Rows += $line.Trim() }
    }
    $out.Add("GatewaySmoke (``$($smokeFile.Name)``, latest run per symbol):")
    foreach ($run in $runs.Values) {
        $out.Add("- $($run.Symbol): $($run.Summary) ($($run.Version), $($run.Time))")
        foreach ($x in $run.Rows) { $out.Add("  - ``$x``") }
    }
}

$target = Join-Path $ProfilesDir 'SUMMARY.md'
[IO.File]::WriteAllText($target, (($out -join "`n") + "`n"), (New-Object Text.UTF8Encoding $false))
Write-Host "OK    $target ($((Get-Item -LiteralPath $target).Length) bytes, $($rows.Count) account(s))"
